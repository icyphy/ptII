package org.ptolemy.agent.tools;

import org.json.JSONArray;
import org.json.JSONObject;
import org.ptolemy.agent.session.PtolemySession;
import org.ptolemy.agent.util.AgentResult;

import ptolemy.actor.IOPort;
import ptolemy.kernel.ComponentEntity;
import ptolemy.kernel.CompositeEntity;
import ptolemy.kernel.Port;
import ptolemy.kernel.util.NamedObj;

///////////////////////////////////////////////////////////////////
//// ConnectTool

/**
 Wire two ports together by creating a fresh
 {@code ptolemy.actor.TypedIORelation} and linking both ports to it.

 <p>The argument shape uses dotted port references because that is
 how MoML itself addresses ports:
 {@code "Ramp1.output"} or {@code "Gain.input"}.

 <p>If a port name does not contain a dot, the tool interprets it as
 a port at top level (rare but legal in Ptolemy).

 <p>Args:
 <ul>
 <li>{@code from} -- required, e.g. {@code "Ramp1.output"}</li>
 <li>{@code to} -- required, e.g. {@code "Gain.input"}</li>
 <li>{@code name} -- optional, name of the relation (autogenerated
     otherwise)</li>
 </ul>

 @author Ptolemy II Agent contributors
 @version $Id$
 @since Ptolemy II 11.1
 */
public class ConnectTool implements AgentTool {

    @Override
    public String name() {
        return "connect";
    }

    @Override
    public String description() {
        return "Connect two ports through a new relation. Port names use"
                + " the MoML \"entity.port\" syntax (for example"
                + " \"Ramp1.output\" or \"Gain.input\").";
    }

    @Override
    public JSONObject parametersSchema() {
        JSONObject props = new JSONObject();
        props.put("from", new JSONObject().put("type", "string")
                .put("description",
                        "Source port reference, e.g. \"Ramp1.output\"."));
        props.put("to", new JSONObject().put("type", "string")
                .put("description",
                        "Destination port reference, e.g. \"Gain.input\"."));
        props.put("name", new JSONObject().put("type", "string")
                .put("description",
                        "Optional relation name. Auto-generated when"
                                + " omitted."));
        props.put("parent", new JSONObject().put("type", "string")
                .put("description",
                        "Optional name of the enclosing composite. When"
                                + " set, the relation lives inside the"
                                + " composite and port refs are interpreted"
                                + " relative to it."));

        JSONObject schema = new JSONObject();
        schema.put("type", "object");
        schema.put("properties", props);
        schema.put("required", new JSONArray().put("from").put("to"));
        return schema;
    }

    @Override
    public AgentResult execute(PtolemySession session, JSONObject args) {
        if (!args.has("from") || !args.has("to")) {
            return AgentResult.fail("connect requires 'from' and 'to'");
        }
        String from = args.getString("from").trim();
        String to = args.getString("to").trim();
        String relName = args.optString("name", "").trim();
        String parent = args.optString("parent", "").trim();

        if (session.toplevel() == null) {
            return AgentResult.fail("no model loaded");
        }
        CompositeEntity top = (CompositeEntity) session.toplevel();

        // Resolve the scope: top-level by default, or the named child
        // composite if `parent` was supplied.
        CompositeEntity scope = top;
        if (parent.length() > 0) {
            ptolemy.kernel.ComponentEntity child = top.getEntity(parent);
            if (!(child instanceof CompositeEntity)) {
                return AgentResult.fail(
                        "no composite named '" + parent + "' at top level");
            }
            scope = (CompositeEntity) child;
        }

        IOPort source = resolvePort(scope, from);
        if (source == null) {
            return AgentResult.fail("source port not found: " + from);
        }
        // A boundary input on the scope itself acts as a source from
        // inside; treat it as such.
        boolean sourceOk = source.isOutput()
                || (source.getContainer() == scope && source.isInput());
        if (!sourceOk) {
            return AgentResult.fail("source is not a valid output: " + from);
        }
        IOPort destination = resolvePort(scope, to);
        if (destination == null) {
            return AgentResult.fail("destination port not found: " + to);
        }
        boolean destOk = destination.isInput()
                || (destination.getContainer() == scope
                        && destination.isOutput());
        if (!destOk) {
            return AgentResult.fail(
                    "destination is not a valid input: " + to);
        }

        // Fan-out handling. If the source port is a NON-multiport that
        // is already linked to a relation, creating a new relation on
        // it would fail with "Attempt to link more than one relation
        // to a single port". Instead, reuse the existing relation and
        // just add the destination as another <link>. This makes the
        // simple, intuitive workflow ("call connect once per consumer")
        // actually work, the way the previous prompt promised.
        boolean userPickedRelation = !relName.isEmpty();
        ptolemy.kernel.Relation reusableRelation = null;
        if (!source.isMultiport()) {
            java.util.List<?> existing = source.linkedRelationList();
            for (Object obj : existing) {
                if (obj instanceof ptolemy.kernel.Relation) {
                    reusableRelation = (ptolemy.kernel.Relation) obj;
                    break;
                }
            }
        }

        String moml;
        boolean fannedOut = false;
        if (reusableRelation != null && !userPickedRelation) {
            // Fan-out from a single-port: only emit a NEW <link> to
            // the existing relation, no new <relation>.
            relName = reusableRelation.getName();
            String inner = "<group>"
                    + "<link port=\"" + AddEntityTool.escape(to)
                    + "\" relation=\""
                    + AddEntityTool.escape(relName) + "\"/>"
                    + "</group>";
            moml = parent.length() == 0
                    ? inner
                    : "<entity name=\""
                            + AddEntityTool.escape(parent) + "\">"
                            + inner + "</entity>";
            fannedOut = true;
        } else {
            if (relName.isEmpty()) {
                relName = uniqueRelationName(scope);
            } else if (scope.getRelation(relName) != null) {
                return AgentResult.fail(
                        "relation already exists: " + relName);
            }
            String inner = "<group>"
                    + "<relation name=\""
                    + AddEntityTool.escape(relName) + "\""
                    + " class=\"ptolemy.actor.TypedIORelation\"/>"
                    + "<link port=\"" + AddEntityTool.escape(from)
                    + "\" relation=\""
                    + AddEntityTool.escape(relName) + "\"/>"
                    + "<link port=\"" + AddEntityTool.escape(to)
                    + "\" relation=\""
                    + AddEntityTool.escape(relName) + "\"/>"
                    + "</group>";
            moml = parent.length() == 0
                    ? inner
                    : "<entity name=\""
                            + AddEntityTool.escape(parent) + "\">"
                            + inner + "</entity>";
        }

        AgentResult res = session.applyChange(moml);
        if (!res.ok()) {
            return res;
        }
        JSONObject data = new JSONObject();
        data.put("relation", relName);
        data.put("from", from);
        data.put("to", to);
        data.put("parent", parent);
        data.put("fannedOut", fannedOut);
        String msg = fannedOut
                ? "fan-out: " + from + " -> " + to + " (reused "
                        + relName + ")"
                : "connected " + from + " -> " + to;
        return AgentResult.ok(msg, data);
    }

    private static String uniqueRelationName(CompositeEntity top) {
        for (int i = 0; i < 1_000_000; i++) {
            String candidate = "rel" + i;
            NamedObj existing = top.getRelation(candidate);
            if (existing == null) {
                return candidate;
            }
        }
        return "rel" + System.nanoTime();
    }

    static IOPort resolvePort(CompositeEntity scope, String reference) {
        if (scope == null || reference == null || reference.length() == 0) {
            return null;
        }
        int dot = reference.lastIndexOf('.');
        Port port;
        if (dot < 0) {
            // No entity prefix means a port on the scope itself
            // (boundary port) — common when wiring inside a composite.
            port = scope.getPort(reference);
        } else {
            String entityName = reference.substring(0, dot);
            String portName = reference.substring(dot + 1);
            ComponentEntity entity = scope.getEntity(entityName);
            if (entity == null) {
                return null;
            }
            port = entity.getPort(portName);
        }
        return port instanceof IOPort ? (IOPort) port : null;
    }
}
