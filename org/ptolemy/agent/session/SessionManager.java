package org.ptolemy.agent.session;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.concurrent.ConcurrentHashMap;

import org.json.JSONArray;

///////////////////////////////////////////////////////////////////
//// SessionManager

/**
 Process-wide registry of {@link PtolemySession} instances. Used by the
 HTTP layer to look up the right session for an incoming request and
 to dispose them on demand. Thread-safe; intended to be a singleton.

 @author Ptolemy II Agent contributors
 @version $Id$
 @since Ptolemy II 11.1
 */
public class SessionManager {

    private static final SessionManager INSTANCE = new SessionManager();
    /** Default blank model loaded for every newly created session.
     *  This guarantees tool calls (e.g. add_entity) can run immediately
     *  without requiring an explicit /load step first. */
    private static final String DEFAULT_SDF_MODEL =
            "<?xml version=\"1.0\" standalone=\"no\"?>"
            + "<!DOCTYPE entity PUBLIC \"-//UC Berkeley//DTD MoML 1//EN\" "
            + "\"http://ptolemy.eecs.berkeley.edu/xml/dtd/MoML_1.dtd\">"
            + "<entity name=\"AutoModel\" class=\"ptolemy.actor.TypedCompositeActor\">"
            + "<property name=\"_createdBy\" class=\"ptolemy.kernel.attributes.VersionAttribute\""
            + " value=\"11.1.devel\"/>"
            + "<property name=\"SDF Director\" class=\"ptolemy.domains.sdf.kernel.SDFDirector\">"
            + "<property name=\"iterations\" class=\"ptolemy.data.expr.Parameter\""
            + " value=\"50\"/>"
            + "</property>"
            + "</entity>";

    private final ConcurrentHashMap<String, PtolemySession> _byId = new ConcurrentHashMap<>();

    private SessionManager() {
    }

    /** @return The shared singleton. */
    public static SessionManager get() {
        return INSTANCE;
    }

    /** Create a new session with an autogenerated id.
     *  @return The freshly registered session.
     *  @throws Exception If session initialization fails.
     */
    public PtolemySession create() throws Exception {
        PtolemySession session = new PtolemySession();
        org.ptolemy.agent.util.AgentResult loadResult =
                session.loadMoml(DEFAULT_SDF_MODEL);
        if (!loadResult.ok()) {
            throw new Exception(
                    "could not initialize default model: "
                    + loadResult.message());
        }
        _byId.put(session.id(), session);
        return session;
    }

    /** Look up a session by id.
     *  @param id The session id.
     *  @return The session, or null if unknown.
     */
    public PtolemySession find(String id) {
        return _byId.get(id);
    }

    /** Remove a session, releasing its model. Safe to call with a
     *  stale id (returns false).
     *  @param id The session id.
     *  @return True iff the session existed and was disposed.
     */
    public boolean remove(String id) {
        PtolemySession session = _byId.remove(id);
        if (session != null) {
            session.disposeModel();
            return true;
        }
        return false;
    }

    /** @return Snapshot list of every registered session. */
    public List<PtolemySession> all() {
        return new ArrayList<>(_byId.values());
    }

    /** @return JSON array summarizing every registered session. */
    public JSONArray toJsonArray() {
        JSONArray arr = new JSONArray();
        Collection<PtolemySession> sessions = _byId.values();
        for (PtolemySession session : sessions) {
            arr.put(session.summary());
        }
        return arr;
    }
}
